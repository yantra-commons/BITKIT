import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { buildCss, flatten, type TokenSource } from '../src/lib.ts';

const tokens = JSON.parse(
  readFileSync(new URL('../src/tokens.json', import.meta.url), 'utf8'),
) as TokenSource;
const out = new URL('../dist/', import.meta.url);
mkdirSync(out, { recursive: true });

const css = buildCss(tokens);
writeFileSync(new URL('tokens.css', out), css);

const vars = Object.fromEntries([...flatten(tokens.base), ...flatten(tokens.themes.light)]);
const names = Object.keys(vars);

const js = `// Generated by scripts/build.ts — do not edit.
/** Full token stylesheet (same as tokens.css). Injected by @orange-ui/elements. */
export const cssText = ${JSON.stringify(css)};
/** Raw token source. */
export const tokens = ${JSON.stringify({ base: tokens.base, themes: tokens.themes })};
/** Every CSS custom property name defined by the kit. */
export const cssVariables = ${JSON.stringify(names)};
/** Default (light) values keyed by CSS variable name. */
export const defaults = ${JSON.stringify(vars)};
/** Reference a token as a CSS var() expression, e.g. cssVar('color-accent'). */
export const cssVar = (name) => \`var(--ou-\${name})\`;
`;
writeFileSync(new URL('index.js', out), js);

const dts = `export declare const cssText: string;
export interface ThemeTokens { color: Record<string, string>; shadow: Record<string, string>; }
export declare const tokens: { base: Record<string, Record<string, string>>; themes: { light: ThemeTokens; dark: ThemeTokens } };
export type CssVariable =\n${names.map((n) => `  | ${JSON.stringify(n)}`).join('\n')};
export declare const cssVariables: CssVariable[];
export declare const defaults: Record<CssVariable, string>;
export declare const cssVar: (name: string) => string;
`;
writeFileSync(new URL('index.d.ts', out), dts);
console.log(`tokens: ${names.length} variables written to dist/`);
