// Generates src/internal/icons.generated.ts from @bitcoin-design/bitcoin-icons-svg (MIT).
// Only the curated subset below is included, so the runtime ships no icon dependency.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);

/** kit name -> [style, Bitcoin Icons name] */
const ICONS = {
  alert: ['outline', 'Alert'],
  'alert-circle': ['outline', 'AlertCircle'],
  'arrow-down': ['outline', 'ArrowDown'],
  'arrow-up': ['outline', 'ArrowUp'],
  bitcoin: ['outline', 'Bitcoin'],
  'bitcoin-circle': ['filled', 'BitcoinCircle'],
  camera: ['outline', 'Camera'],
  'caret-down': ['outline', 'CaretDown'],
  check: ['outline', 'Check'],
  clock: ['outline', 'Clock'],
  coins: ['outline', 'Coins'],
  confirmations0: ['outline', 'Confirmations0'],
  confirmations1: ['outline', 'Confirmations1'],
  confirmations2: ['outline', 'Confirmations2'],
  confirmations3: ['outline', 'Confirmations3'],
  confirmations4: ['outline', 'Confirmations4'],
  confirmations5: ['outline', 'Confirmations5'],
  confirmations6: ['outline', 'Confirmations6'],
  copy: ['outline', 'Copy'],
  cross: ['outline', 'Cross'],
  edit: ['outline', 'Edit'],
  exchange: ['outline', 'Exchange'],
  export: ['outline', 'Export'],
  hidden: ['outline', 'Hidden'],
  info: ['outline', 'InfoCircle'],
  invoice: ['outline', 'Invoice'],
  key: ['outline', 'Key'],
  lightning: ['filled', 'Lightning'],
  link: ['outline', 'Link'],
  lock: ['outline', 'Lock'],
  mnemonic: ['outline', 'Mnemonic'],
  plus: ['outline', 'Plus'],
  'qr-code': ['outline', 'QrCode'],
  receive: ['outline', 'Receive'],
  refresh: ['outline', 'Refresh'],
  scan: ['outline', 'Scan'],
  send: ['outline', 'Send'],
  share: ['outline', 'Share'],
  shield: ['outline', 'Shield'],
  'tip-jar': ['outline', 'TipJar'],
  transactions: ['outline', 'Transactions'],
  visible: ['outline', 'Visible'],
  wallet: ['outline', 'Wallet'],
};

const out = {};
for (const [name, [style, src]] of Object.entries(ICONS)) {
  const { svg } = require(`@bitcoin-design/bitcoin-icons-svg/${style}/${src}Icon.js`);
  const body = svg
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  out[name] = { filled: style === 'filled', body };
}

const ts = `// Generated by scripts/gen-icons.mjs from Bitcoin Icons (https://bitcoinicons.com, MIT).
// Do not edit by hand.
export const ICONS = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, { filled: boolean; body: string }>;

export type IconName = keyof typeof ICONS;
`;
writeFileSync(new URL('../src/internal/icons.generated.ts', import.meta.url), ts);
console.log(`icons: ${Object.keys(out).length} written`);
